/**
 * Generates sample files on the fly, so people can try the app without picking their own
 * files (and the repository does not need to ship binary samples).
 */

import { canvasToBlob } from './canvas'

function samplePhoto(): HTMLCanvasElement {
  const w = 1600
  const h = 1067
  const canvas = document.createElement('canvas')
  canvas.width = w
  canvas.height = h
  const ctx = canvas.getContext('2d')!

  const sky = ctx.createLinearGradient(0, 0, 0, h * 0.7)
  sky.addColorStop(0, '#1d2b64')
  sky.addColorStop(0.55, '#7b6ea8')
  sky.addColorStop(1, '#f8b59a')
  ctx.fillStyle = sky
  ctx.fillRect(0, 0, w, h)

  const sun = ctx.createRadialGradient(w * 0.68, h * 0.5, 10, w * 0.68, h * 0.5, 260)
  sun.addColorStop(0, 'rgba(255, 236, 190, 1)')
  sun.addColorStop(0.25, 'rgba(255, 210, 150, 0.85)')
  sun.addColorStop(1, 'rgba(255, 180, 140, 0)')
  ctx.fillStyle = sun
  ctx.fillRect(0, 0, w, h)

  const ridge = (base: number, amplitude: number, seed: number, color: string) => {
    ctx.beginPath()
    ctx.moveTo(0, h)
    for (let x = 0; x <= w; x += 8) {
      const y =
        base -
        amplitude * (0.55 * Math.sin(x / 210 + seed) + 0.3 * Math.sin(x / 97 + seed * 2)) -
        amplitude * 0.15 * Math.sin(x / 41 + seed * 3)
      ctx.lineTo(x, y)
    }
    ctx.lineTo(w, h)
    ctx.closePath()
    ctx.fillStyle = color
    ctx.fill()
  }
  ridge(h * 0.62, 90, 1.3, '#6c5b8e')
  ridge(h * 0.7, 80, 4.1, '#4a3f6b')
  ridge(h * 0.8, 60, 2.2, '#2e2a4a')

  const lake = ctx.createLinearGradient(0, h * 0.82, 0, h)
  lake.addColorStop(0, '#3b3a63')
  lake.addColorStop(1, '#141428')
  ctx.fillStyle = lake
  ctx.fillRect(0, h * 0.84, w, h * 0.16)
  ctx.fillStyle = 'rgba(255, 220, 170, 0.35)'
  for (let i = 0; i < 9; i++) {
    const y = h * 0.86 + i * 16
    const half = 140 - i * 12
    ctx.fillRect(w * 0.68 - half, y, half * 2, 3)
  }
  return canvas
}

export async function createSampleImage(): Promise<File> {
  const blob = await canvasToBlob(samplePhoto(), 'image/jpeg', 0.9)
  return new File([blob], 'sample-photo.jpg', { type: 'image/jpeg' })
}

const LOREM = [
  'This agreement is made between the parties listed below. It describes the services to',
  'be provided, the fees payable for them and the obligations of each party. Copies of',
  'identity documents attached to this agreement are provided solely for its execution',
  'and must not be used for any other purpose. All information is confidential and must',
  'not be disclosed to third parties without prior written consent.',
]

export async function createSamplePdf(): Promise<File> {
  const { PDFDocument, StandardFonts, rgb } = await import('pdf-lib')
  const doc = await PDFDocument.create()
  doc.setTitle('SafeMark sample document')
  const regular = await doc.embedFont(StandardFonts.Helvetica)
  const bold = await doc.embedFont(StandardFonts.HelveticaBold)
  const ink = rgb(0.13, 0.15, 0.19)
  const muted = rgb(0.42, 0.46, 0.52)
  const accent = rgb(0.06, 0.52, 0.53)

  // Page 1: a portrait A4 "agreement" with text and a table.
  const page = doc.addPage([595.28, 841.89])
  page.drawRectangle({ x: 0, y: 801, width: 595.28, height: 41, color: accent })
  page.drawText('SAMPLE SERVICE AGREEMENT', { x: 56, y: 760, size: 20, font: bold, color: ink })
  page.drawText('No. 2026-0042  ·  Generated by SafeMark for demonstration', {
    x: 56,
    y: 740,
    size: 10,
    font: regular,
    color: muted,
  })
  let y = 700
  for (const paragraph of [LOREM, LOREM.slice(1, 4)]) {
    for (const line of paragraph) {
      page.drawText(line, { x: 56, y, size: 11, font: regular, color: ink })
      y -= 17
    }
    y -= 12
  }
  const rows = [
    ['Item', 'Quantity', 'Unit price', 'Amount'],
    ['Consulting', '12 h', '120.00', '1,440.00'],
    ['Design review', '1', '600.00', '600.00'],
    ['Support plan', '3 months', '90.00', '270.00'],
    ['Total', '', '', '2,310.00'],
  ]
  const cols = [56, 236, 346, 456]
  y -= 10
  rows.forEach((row, r) => {
    if (r === 0)
      page.drawRectangle({ x: 50, y: y - 7, width: 495, height: 24, color: rgb(0.93, 0.95, 0.96) })
    row.forEach((cell, c) =>
      page.drawText(cell, {
        x: cols[c]!,
        y,
        size: 11,
        font: r === 0 || r === 4 ? bold : regular,
        color: ink,
      }),
    )
    page.drawLine({
      start: { x: 50, y: y - 8 },
      end: { x: 545, y: y - 8 },
      thickness: 0.6,
      color: muted,
    })
    y -= 26
  })
  page.drawLine({ start: { x: 56, y: 150 }, end: { x: 236, y: 150 }, thickness: 0.8, color: ink })
  page.drawLine({ start: { x: 346, y: 150 }, end: { x: 526, y: 150 }, thickness: 0.8, color: ink })
  page.drawText('Signature (Party A)', { x: 56, y: 134, size: 10, font: regular, color: muted })
  page.drawText('Signature (Party B)', { x: 346, y: 134, size: 10, font: regular, color: muted })

  // Page 2: a landscape page with a chart, to show mixed page sizes.
  const chart = doc.addPage([841.89, 595.28])
  chart.drawText('Appendix: quarterly figures', { x: 56, y: 530, size: 18, font: bold, color: ink })
  const values = [42, 58, 51, 74, 66, 88, 79, 95]
  values.forEach((value, i) => {
    const x = 80 + i * 88
    chart.drawRectangle({
      x,
      y: 90,
      width: 52,
      height: value * 4,
      color: i % 2 ? accent : rgb(0.36, 0.45, 0.85),
    })
    chart.drawText(`Q${(i % 4) + 1}`, { x: x + 16, y: 70, size: 11, font: regular, color: muted })
  })
  chart.drawLine({ start: { x: 60, y: 88 }, end: { x: 790, y: 88 }, thickness: 1, color: ink })

  const bytes = await doc.save()
  return new File([bytes as Uint8Array<ArrayBuffer>], 'sample-document.pdf', {
    type: 'application/pdf',
  })
}
